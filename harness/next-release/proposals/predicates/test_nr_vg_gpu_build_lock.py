"""Closure predicate for NR-VG-GPU-BUILD-LOCK (merged into graph.json on 2026-11-08).

Flips green only when harness/vision/gpu_build_lock/build_lock_receipt.json is
committed and records: verdict "built"; a build root under E:/OpenCV5.1_Prep (R3);
the pinned opencv and opencv_contrib commits; a module list GENERATED by configure
(not the requested BUILD_LIST) that covers the R2 change-mask chain (cudaarithm,
cudafilters) plus core, imgproc and python3; a CPython 3.12.10 cp312 binding with
the limited API off (R4); the install step and a cv2 that landed inside the declared
worker venv; sha256 digests of the native files; OPENCV_ENABLE_NONFREE=OFF; measured
build windows; and Joe's per-act authorization.

Red when written (C0, 2026-11-07): the receipt is not committed (marker below).

Reads committed files only. It never configures, builds, installs, imports cv2,
touches a GPU, launches Houdini, trains or uses the network - even if a build exists.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path


def _repo_root() -> Path:
    """Find the repository root from the working directory, never from this file's
    location, so the predicate keeps working wherever it is moved (review G1)."""
    here = Path.cwd().resolve()
    for p in (here, *here.parents):
        if (p / ".git").exists() and (p / "harness" / "next-release" / "graph.json").is_file():
            return p
    r = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, timeout=60)
    if r.returncode == 0 and r.stdout.strip():
        return Path(r.stdout.strip()).resolve()
    raise AssertionError("repository root not found: run this predicate from inside the SYNAPSE checkout")


ROOT = _repo_root()
MARKER = ("NR-VG-GPU-BUILD-LOCK RED: no committed build-lock receipt "
          "harness/vision/gpu_build_lock/build_lock_receipt.json")
RECEIPT = "harness/vision/gpu_build_lock/build_lock_receipt.json"
OPENCV_SHA = "e4f78fbcf1a773fbed69e14500e8b734963eb585"
CONTRIB_SHA = "b67a855188a3d683813731010f6d39ac614733a4"
HEX64 = re.compile(r"^[0-9a-f]{64}$")


def _committed(rel: str) -> bool:
    if not (ROOT / rel).is_file():
        return False
    r = subprocess.run(["git", "-C", str(ROOT), "ls-files", "--error-unmatch", "--", rel],
                       capture_output=True, text=True, timeout=60)
    return r.returncode == 0


def _receipt() -> dict:
    if not _committed(RECEIPT):
        raise AssertionError(MARKER)
    return json.loads((ROOT / RECEIPT).read_text(encoding="utf-8"))


def _norm(p: str) -> str:
    return str(p).replace("\\", "/").rstrip("/").lower()


def test_build_lock_receipt_is_committed():
    r = _receipt()
    assert isinstance(r, dict) and r, "the committed receipt is empty"


def test_built_under_the_ruled_root():
    r = _receipt()
    assert r.get("verdict", {}).get("state") == "built", "verdict.state is not 'built'"
    root = _norm(r.get("build_root", ""))
    # Compare path components, so a sibling such as E:/OpenCV5.1_Prep_old does not pass.
    assert root == "e:/opencv5.1_prep" or root.startswith("e:/opencv5.1_prep/"), \
        "R3: build_root is not under E:/OpenCV5.1_Prep"


def test_sources_are_the_pinned_commits():
    s = _receipt().get("sources", {})
    assert s.get("opencv") == OPENCV_SHA and s.get("opencv_contrib") == CONTRIB_SHA, "source SHAs differ from the pinned pair"


def test_generated_modules_cover_the_change_mask_chain():
    m = _receipt().get("modules", {})
    assert m.get("source") == "configure_log", "module list must come from the configure log, not the requested BUILD_LIST"
    missing = {"core", "imgproc", "cudaarithm", "cudafilters", "python3"} - set(m.get("generated", []))
    assert not missing, f"R2 chain modules not generated: {sorted(missing)}"


def test_binding_is_cpython_3_12_10_without_limited_api():
    p = _receipt().get("python", {})
    assert p.get("version") == "3.12.10", "R4: binding interpreter is not CPython 3.12.10"
    assert p.get("abi_tag") == "cp312" and p.get("limited_api") is False, "R4: binding must be cp312 with the limited API off"


def test_install_step_and_cv2_location():
    i = _receipt().get("install", {})
    assert isinstance(i.get("command"), str) and i["command"].strip(), "no install step recorded (the staged recipe has none)"
    venv = _norm(i.get("worker_venv", ""))
    assert venv and _norm(i.get("cv2_file", "")).startswith(venv + "/"), "cv2 did not land inside the declared worker venv"


def test_native_files_are_digested():
    files = _receipt().get("native_files", [])
    assert files, "no native-file digests"
    for f in files:
        assert f.get("path") and HEX64.match(str(f.get("sha256", ""))), f"bad native-file entry: {f!r}"


def test_nonfree_is_off():
    assert _receipt().get("cmake_cache", {}).get("OPENCV_ENABLE_NONFREE") == "OFF", "OPENCV_ENABLE_NONFREE is not OFF"


def test_windows_measured_and_authorized():
    r = _receipt()
    wins = r.get("build_windows", [])
    assert wins and all(w.get("started") and w.get("ended") and w.get("measured") is True for w in wins), \
        "build windows must carry measured start and end times"
    a = r.get("authorization", {})
    assert a.get("by") == "Joe" and a.get("date"), "no per-act authorization by Joe recorded"
